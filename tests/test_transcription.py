"""
Unit tests for TranscriptionService and video/audio support in FileParserService.

Real ffmpeg audio extraction is exercised directly — ffmpeg is a hard runtime dependency
of this feature, and that's the integration most likely to break (missing binary, wrong
flags), so mocking it away would hide exactly what needs testing. The Whisper model
itself is mocked: downloading and running it in CI would be slow and non-deterministic,
the same tradeoff test_rag.py makes for live Ollama calls.
"""

import os
import shutil
import subprocess
import tempfile
from types import SimpleNamespace
from unittest.mock import MagicMock, patch

import pytest
from fastapi.testclient import TestClient

from backend.main import app
from backend.models.summary import SummaryResponse
from backend.services.extraction_cache import extraction_cache
from backend.services.file_parser import FileParserService
from backend.services.transcription_service import TranscriptionService

client = TestClient(app)

FFMPEG_AVAILABLE = shutil.which("ffmpeg") is not None
requires_ffmpeg = pytest.mark.skipif(
    not FFMPEG_AVAILABLE, reason="ffmpeg is required for video/audio transcription"
)


def _fake_segment(text: str) -> SimpleNamespace:
    return SimpleNamespace(text=text)


def _fake_model(*texts: str) -> SimpleNamespace:
    """A stand-in for a loaded faster-whisper WhisperModel."""
    segments = [_fake_segment(text) for text in texts]
    return SimpleNamespace(
        transcribe=lambda audio_path, beam_size: (segments, SimpleNamespace(language="en"))
    )


@pytest.fixture
def silent_audio_file():
    """A short, real WAV file generated by ffmpeg (silence, not speech)."""
    fd, path = tempfile.mkstemp(suffix=".wav")
    os.close(fd)
    subprocess.run(
        ["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono", "-t", "1", path],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    yield path
    os.remove(path)


def test_file_parser_recognizes_video_and_audio_extensions():
    for ext in (".mp4", ".mov", ".mkv", ".webm", ".avi", ".mp3", ".wav", ".m4a"):
        assert ext in FileParserService.SUPPORTED_EXTENSIONS
        assert ext in FileParserService.MEDIA_EXTENSIONS


def test_file_parser_media_gets_a_larger_size_ceiling():
    assert FileParserService.max_size_mb(".mp4") > FileParserService.max_size_mb(".txt")


def test_transcribe_missing_file_raises_value_error():
    with pytest.raises(ValueError):
        TranscriptionService.transcribe("/no/such/file.mp4")


def test_ffmpeg_not_found_raises_clear_runtime_error():
    with patch(
        "backend.services.transcription_service.subprocess.run",
        side_effect=FileNotFoundError,
    ):
        with pytest.raises(RuntimeError, match="ffmpeg"):
            TranscriptionService._extract_audio("/tmp/whatever.mp4", "/tmp/out.wav")


@requires_ffmpeg
def test_transcribe_extracts_audio_and_joins_segments(silent_audio_file):
    """Real ffmpeg extraction, mocked Whisper — verifies segment joining end to end."""
    model = _fake_model("Sarah will finish the report by Friday.", "")

    with patch("backend.services.transcription_service._get_model", return_value=model):
        transcript = TranscriptionService.transcribe(silent_audio_file)

    assert transcript == "Sarah will finish the report by Friday."


@requires_ffmpeg
def test_transcribe_no_speech_returns_empty_string(silent_audio_file):
    """Silence should transcribe to an empty string, not raise."""
    model = _fake_model()

    with patch("backend.services.transcription_service._get_model", return_value=model):
        transcript = TranscriptionService.transcribe(silent_audio_file)

    assert transcript == ""


@requires_ffmpeg
def test_upload_route_transcribes_video(tmp_path):
    """End to end through the real /upload route, with only Whisper itself mocked."""
    video_path = tmp_path / "meeting.mp4"
    subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", "color=c=black:s=64x64:r=1:d=1",
            "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono",
            "-t", "1",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac",
            str(video_path),
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )

    model = _fake_model("Decision: ship on Friday.")

    with patch("backend.services.transcription_service._get_model", return_value=model):
        with open(video_path, "rb") as f:
            response = client.post("/upload", files={"file": ("meeting.mp4", f, "video/mp4")})

    assert response.status_code == 201
    body = response.json()
    assert body["sample_text"] == "Decision: ship on Friday."
    assert body["filename"] == "meeting.mp4"


@requires_ffmpeg
def test_transcription_runs_once_across_upload_chat_and_summarize(tmp_path):
    """
    Reproduces the real frontend flow — the same recording is posted to /upload, then
    /chat/upload, then referenced by /summarize — and proves the expensive step
    (ffmpeg + Whisper transcription) runs exactly once for all three, because the second
    and third calls hit the extraction cache instead of re-transcribing identical bytes.
    """
    extraction_cache.clear()

    video_path = tmp_path / "standup.mp4"
    subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", "color=c=black:s=64x64:r=1:d=1",
            "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono",
            "-t", "1",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac",
            str(video_path),
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    video_bytes = video_path.read_bytes()

    segments = [_fake_segment("Sarah owns the rollout; ships Friday.")]
    model = SimpleNamespace(transcribe=MagicMock(return_value=(segments, SimpleNamespace(language="en"))))

    canned_summary = SummaryResponse(
        executive_summary="The team confirmed the Friday rollout.",
        key_discussion_points=["Rollout ownership", "Friday deadline"],
        meeting_outcome="Rollout proceeds Friday as planned.",
        model_used="qwen3",
        filename="standup.mp4",
    )

    with (
        patch("backend.services.transcription_service._get_model", return_value=model),
        patch("backend.routes.chat.vector_service.generate_embedding", return_value=[0.1, 0.2, 0.3]),
        patch("backend.routes.chat.vector_service.collection") as mock_collection,
        patch("backend.routes.summary.summary_service.generate_summary", return_value=canned_summary),
    ):
        mock_collection.upsert.return_value = None

        upload_response = client.post(
            "/upload", files={"file": ("standup.mp4", video_bytes, "video/mp4")}
        )
        chat_response = client.post(
            "/chat/upload", files={"file": ("standup.mp4", video_bytes, "video/mp4")}
        )
        summarize_response = client.post("/summarize", json={"filename": "standup.mp4"})

    assert upload_response.status_code == 201
    assert chat_response.status_code == 201
    assert summarize_response.status_code == 200

    transcript = "Sarah owns the rollout; ships Friday."
    assert upload_response.json()["sample_text"] == transcript
    assert chat_response.json()["number_of_chunks"] > 0

    # The actual proof: three requests over the same bytes, one real transcription.
    assert model.transcribe.call_count == 1

    extraction_cache.clear()
